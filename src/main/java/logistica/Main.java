    private void btnBFSActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBFSActionPerformed
        String inicio = txtOrigen.getText().trim();

        if (inicio.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese una ciudad de inicio");
            return;
        }

        java.util.List<String> recorrido = grafo.bfs(inicio);

        if (recorrido.isEmpty()) {
            JOptionPane.showMessageDialog(this, "La ciudad no existe");
        } else {
            String mensaje = "Recorrido BFS:\n";

            for (String ciudad : recorrido) {
                mensaje += ciudad + "\n";
            }

            JOptionPane.showMessageDialog(this, mensaje);
        }
    }//GEN-LAST:event_btnBFSActionPerformed

    private void btnRegistrarEntregaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarEntregaActionPerformed
        try {
            int codigo = Integer.parseInt(txtCodigoEntrega.getText());
            int cantidad = Integer.parseInt(txtCantidadEntrega.getText());
            String destino = txtDestinoEntrega.getText().trim();

            if (cantidad <= 0 || destino.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Ingrese datos válidos");
                return;
            }

            // 1. Buscar producto
            Producto producto = arbol.buscar(codigo);

            if (producto == null) {
                JOptionPane.showMessageDialog(this, "Producto no encontrado");
                return;
            }

            // 2. Verificar stock
            if (producto.getStock() < cantidad) {
                JOptionPane.showMessageDialog(this, "Stock insuficiente");
                return;
            }

            // 3. Verificar destino
            if (grafo.bfs(destino).isEmpty()) {
                JOptionPane.showMessageDialog(this, "La ciudad destino no existe");
                return;
            }

            // 4. Verificar camiones
            if (cola.estaVacia()) {
                JOptionPane.showMessageDialog(this, "No hay camiones disponibles");
                return;
            }

            // 5. Descontar stock y retirar camión
            arbol.descontarStock(codigo, cantidad);
            Camion camion = cola.desencolar();

            // 6. Guardar en historial
            Entrega entrega = new Entrega(
                    historial.size() + 1,
                    producto.getNombre(),
                    camion.getPlaca(),
                    destino,
                    cantidad
            );

            historial.add(entrega);

            JOptionPane.showMessageDialog(this,
                    "Entrega registrada correctamente");

            txtCodigoEntrega.setText("");
            txtCantidadEntrega.setText("");
            txtDestinoEntrega.setText("");

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ingrese valores numéricos válidos");
        }
    }//GEN-LAST:event_btnRegistrarEntregaActionPerformed

    private void btnMostrarHistorialActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostrarHistorialActionPerformed
        if (historial.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No hay entregas registradas");
        } else {
            StringBuilder mensaje = new StringBuilder();

            for (Entrega e : historial) {
                mensaje.append(e.toString()).append("\n\n");
            }

            JOptionPane.showMessageDialog(this,
                    mensaje.toString(),
                    "Historial de entregas",
                    JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_btnMostrarHistorialActionPerformed

