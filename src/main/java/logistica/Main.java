    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        try {
            int codigo = Integer.parseInt(txtCodigo.getText());
            String nombre = txtNombre.getText();
            int stock = Integer.parseInt(txtStock.getText());

            if (nombre.isEmpty() || stock < 0) {
                JOptionPane.showMessageDialog(this, "Ingrese datos válidos");
                return;
            }

            Producto p = new Producto(codigo, nombre, stock);
            arbol.insertar(p);

            JOptionPane.showMessageDialog(this, "Producto registrado correctamente");

            txtCodigo.setText("");
            txtNombre.setText("");
            txtStock.setText("");

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ingrese números válidos en código y stock");
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnBsucarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBsucarActionPerformed
        try {
            int codigo = Integer.parseInt(txtCodigo.getText());

            Producto p = arbol.buscar(codigo);

            if (p != null) {
                JOptionPane.showMessageDialog(this,
                        "Producto encontrado:\n"
                        + "Nombre: " + p.getNombre()
                        + "\nStock: " + p.getStock());
            } else {
                JOptionPane.showMessageDialog(this, "Producto no encontrado");
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ingrese un código válido");
        }
    }//GEN-LAST:event_btnBsucarActionPerformed

    private void btnMostrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostrarActionPerformed
        java.util.List<Producto> lista = new java.util.ArrayList<>();

        arbol.inOrden(lista);

        if (lista.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No hay productos registrados");
        } else {
            StringBuilder mensaje = new StringBuilder();

            for (Producto p : lista) {
                mensaje.append(p.toString()).append("\n");
            }

            JOptionPane.showMessageDialog(this, mensaje.toString(),
                    "Inventario ordenado por código",
                    JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_btnMostrarActionPerformed

    private void btnRegistrarCamionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarCamionActionPerformed
        try {
            String placa = txtPlaca.getText();
            String conductor = txtConductor.getText();
            double capacidad = Double.parseDouble(txtCapacidad.getText());

            if (placa.isEmpty() || conductor.isEmpty() || capacidad <= 0) {
                JOptionPane.showMessageDialog(this, "Ingrese datos válidos");
                return;
            }

            Camion camion = new Camion(placa, conductor, capacidad);
            cola.encolar(camion);

            JOptionPane.showMessageDialog(this, "Camión registrado correctamente");

            txtPlaca.setText("");
            txtConductor.setText("");
            txtCapacidad.setText("");

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ingrese una capacidad válida");
        }
    }//GEN-LAST:event_btnRegistrarCamionActionPerformed

    private void btnRetirarCamionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRetirarCamionActionPerformed
        if (cola.estaVacia()) {
            JOptionPane.showMessageDialog(this, "No hay camiones en espera");
        } else {
            Camion camion = cola.desencolar();

            JOptionPane.showMessageDialog(this,
                    "Camión retirado:\n"
                    + "Placa: " + camion.getPlaca()
                    + "\nConductor: " + camion.getConductor());
        }
    }//GEN-LAST:event_btnRetirarCamionActionPerformed

